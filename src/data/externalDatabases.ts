/**
 * Returns complete database references for any rock or mineral
 */
export function getDatabaseRefs(id: string, name?: string): DatabaseReferences {
  if (MINERAL_DATABASE_REFS[id]) {
    return MINERAL_DATABASE_REFS[id];
  }
  if (ROCK_DATABASE_REFS[id]) {
    return ROCK_DATABASE_REFS[id];
  }

  // Generic fallback links based on name
  const queryName = encodeURIComponent(name || id.replace(/^(rock|min)-/, ''));
  return {
    mindatUrl: `https://www.mindat.org/search.php?search=${queryName}`,
    webmineralUrl: `https://webmineral.com/search/search.php?sa=Search&q=${queryName}`,
    rruffUrl: `https://rruff.info/${queryName}`,
    earthChemUrl: `https://search.earthchem.org/?query=${queryName}`,
    georocUrl: 'https://georoc.eu/',
  };
}
